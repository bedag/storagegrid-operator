package metrics

// isElected reports whether the manager's elected channel is closed. A nil
// channel counts as elected, which keeps tests and non-leader-election runs simple.
func isElected(ch <-chan struct{}) bool {
	if ch == nil {
		return true
	}
	select {
	case <-ch:
		return true
	default:
		return false
	}
}
